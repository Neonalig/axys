/**
 * Subsets Bravura to the glyphs Axys sets, and generates `web/src/ui/music.ts` beside it.
 *
 * SMuFL puts every glyph in the private use area, so the subset is specified by codepoint like any
 * other font. Full Bravura is 316 KB; the ranges below come to 16.4 KB, and accidentals alone
 * would be 4.7 KB. Both outputs are committed, so a build and a test run need neither the network
 * nor a Python toolchain.
 *
 * Needs `pyftsubset` on PATH, which comes with fontTools: `pip install fonttools brotli`.
 *
 * Usage: `node scripts/build-music-font.mjs [--check]`. With `--check` nothing is written and the
 * exit status says whether the committed module is what the metadata produces. The woff2 is not
 * compared, because the subsetter is not byte-reproducible across its own versions.
 */

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const HERE = dirname(fileURLToPath(import.meta.url));
const FONT_OUT = resolve(HERE, '..', 'web', 'src', 'fonts', 'bravura-subset.woff2');
const MODULE_OUT = resolve(HERE, '..', 'web', 'src', 'ui', 'music.ts');

const BRAVURA =
  'https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/otf/Bravura.otf';
const METRICS =
  'https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/Bravura.json';
const NAMES = 'https://raw.githubusercontent.com/w3c/smufl/gh-pages/metadata/glyphnames.json';

/**
 * The codepoint ranges shipped, inclusive at both ends.
 *
 * @remarks Locked by the design maturity document. Widening a range widens the file, so measure
 * against the 16.4 KB budget before adding one.
 */
const RANGES = [
  { from: 0xe260, to: 0xe264, what: 'accidentals' },
  { from: 0xe1d2, to: 0xe1db, what: 'noteheads and stemmed notes' },
  { from: 0xe1e7, to: 0xe1e7, what: 'augmentation dot' },
  { from: 0xe4e3, to: 0xe4e7, what: 'rests' },
  { from: 0xe080, to: 0xe09f, what: 'time signature digits' },
  { from: 0xeca0, to: 0xeca9, what: 'metronome marks' },
];

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${String(response.status)}`);
  return response.json();
}

async function fetchBinary(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${String(response.status)}`);
  return Buffer.from(await response.arrayBuffer());
}

function hex(codepoint) {
  return codepoint.toString(16).toUpperCase().padStart(4, '0');
}

function shipped(codepoint) {
  return RANGES.some((range) => codepoint >= range.from && codepoint <= range.to);
}

function render(glyphs) {
  const names = glyphs.map((glyph) => `  | '${glyph.name}'`).join('\n');
  const chars = glyphs
    .map((glyph) => `  ${glyph.name}: '\\u{${hex(glyph.codepoint)}}',`)
    .join('\n');
  const boxes = glyphs
    .map(
      (glyph) =>
        `  ${glyph.name}: { north: ${String(glyph.north)}, south: ${String(glyph.south)} },`,
    )
    .join('\n');
  const ranges = RANGES.map(
    (range) => ` * - \`U+${hex(range.from)}\`–\`U+${hex(range.to)}\`, ${range.what}`,
  ).join('\n');
  return `// SPDX-License-Identifier: AGPL-3.0-or-later

/*
 * Generated by \`node scripts/build-music-font.mjs\`. Do not edit by hand.
 *
 * Names and codepoints from the SMuFL specification, extents from Bravura's own metadata. The
 * shipped subset covers:
 *
${ranges}
 */

/** Name of one music glyph, as SMuFL names it. */
export type MusicGlyph =
${names};

/**
 * The character each glyph is set with.
 *
 * @remarks SMuFL places every glyph in the private use area, so these are meaningless in any
 * other font. Always set them in a run of their own; see {@link musicMarkup}.
 */
export const MUSIC_CHARS: Readonly<Record<MusicGlyph, string>> = {
${chars}
};

/**
 * How far a glyph reaches above and below the baseline, in staff spaces.
 *
 * @remarks From Bravura's \`glyphBBoxes\`. A staff space is a quarter of the em, so a glyph
 * reaching 1.4 spaces above the baseline reaches 0.35em above it.
 */
export const MUSIC_EXTENTS: Readonly<Record<MusicGlyph, { north: number; south: number }>> = {
${boxes}
};

/** Staff spaces in one em, which SMuFL fixes at four. */
export const SPACES_PER_EM = 4;

/**
 * A glyph as markup, set in its own run at its own size.
 *
 * @remarks Never let a music glyph inherit the body text's size or baseline: SMuFL draws to a
 * staff, not to a text baseline, so an accidental set inline at the label's own size sits low and
 * small. The span is sized from the em and shifted so the glyph's own centre lands on the text's
 * centre. \`label\` becomes the accessible name, because the codepoint reads as nothing.
 */
export function musicMarkup(glyph: MusicGlyph, label: string): string {
  const extent = MUSIC_EXTENTS[glyph];
  const centre = ((extent.north + extent.south) / 2 / SPACES_PER_EM).toFixed(3);
  return (
    \`<span class="axys-smufl" role="img" aria-label="\${label}" \` +
    \`style="--axys-smufl-shift: \${centre}em">\${MUSIC_CHARS[glyph]}</span>\`
  );
}

/**
 * Sharp, flat and natural for running text.
 *
 * @remarks The ordinary Unicode musical symbols, not SMuFL. A label carrying one of these must
 * not pull a 16 KB font in behind it, and every UI face has them.
 */
export const TEXT_ACCIDENTALS = {
  sharp: '\\u{266F}',
  flat: '\\u{266D}',
  natural: '\\u{266E}',
} as const;
`;
}

const [names, metrics] = await Promise.all([fetchJson(NAMES), fetchJson(METRICS)]);
const glyphs = Object.entries(names)
  .map(([name, entry]) => ({ name, codepoint: parseInt(entry.codepoint.slice(2), 16) }))
  .filter((glyph) => shipped(glyph.codepoint))
  .sort((a, b) => a.codepoint - b.codepoint)
  // A combining glyph has no bounding box of its own and is not set on its own either, so it
  // stays in the font and out of the module.
  .filter((glyph) => metrics.glyphBBoxes[glyph.name] !== undefined)
  .map((glyph) => {
    const box = metrics.glyphBBoxes[glyph.name];
    return { ...glyph, north: box.bBoxNE[1], south: box.bBoxSW[1] };
  });

const generated = await format(render(glyphs), {
  ...(await resolveConfig(MODULE_OUT)),
  filepath: MODULE_OUT,
});

if (process.argv.includes('--check')) {
  if (readFileSync(MODULE_OUT, 'utf8') !== generated) {
    console.error('web/src/ui/music.ts is not what the SMuFL metadata produces.');
    process.exit(1);
  }
  console.log(`music.ts matches the metadata, ${String(glyphs.length)} glyphs.`);
  process.exit(0);
}

const work = mkdtempSync(join(tmpdir(), 'axys-bravura-'));
try {
  const source = join(work, 'Bravura.otf');
  writeFileSync(source, await fetchBinary(BRAVURA));
  execFileSync('pyftsubset', [
    source,
    `--output-file=${FONT_OUT}`,
    '--flavor=woff2',
    '--layout-features=*',
    '--no-hinting',
    '--desubroutinize',
    `--unicodes=${RANGES.map((range) => `U+${hex(range.from)}-${hex(range.to)}`).join(',')}`,
  ]);
} finally {
  rmSync(work, { recursive: true, force: true });
}

writeFileSync(MODULE_OUT, generated);
const size = readFileSync(FONT_OUT).length;
console.log(
  `Wrote ${FONT_OUT}, ${(size / 1024).toFixed(1)} KB, and ${String(glyphs.length)} glyphs into music.ts.`,
);
if (size > 17 * 1024) {
  console.error(`The subset is over its 16.4 KB budget at ${(size / 1024).toFixed(1)} KB.`);
  process.exit(1);
}
